-- ThemeGram 4.0: additive engagement tables.
-- Run manually in Supabase SQL Editor after reviewing the existing schema.
-- Existing users/themes are not modified or deleted.

CREATE TABLE IF NOT EXISTS public.themegram_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id bigint NOT NULL,
    event_name text NOT NULL CHECK (length(event_name) BETWEEN 1 AND 64),
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS themegram_events_created_at_idx
    ON public.themegram_events (created_at DESC);
CREATE INDEX IF NOT EXISTS themegram_events_name_created_idx
    ON public.themegram_events (event_name, created_at DESC);
CREATE INDEX IF NOT EXISTS themegram_events_user_created_idx
    ON public.themegram_events (telegram_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.themegram_favorites (
    telegram_id bigint NOT NULL,
    theme_id text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (telegram_id, theme_id)
);
CREATE INDEX IF NOT EXISTS themegram_favorites_theme_idx
    ON public.themegram_favorites (theme_id);

-- Keep access server-side; the bot uses the Supabase service-role key.
ALTER TABLE public.themegram_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.themegram_favorites ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.themegram_events FROM anon, authenticated;
REVOKE ALL ON public.themegram_favorites FROM anon, authenticated;
